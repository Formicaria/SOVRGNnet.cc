/// First candidate that binds on loopback. Binding and releasing is the only
/// honest availability test; anything else races less and lies more.
fn pick_port(candidates: &[u16]) -> Result<u16, String> {
    for &port in candidates {
        if TcpListener::bind(("127.0.0.1", port)).is_ok() {
            return Ok(port);
        }
    }
    Err("no free port in range".to_string())
}

