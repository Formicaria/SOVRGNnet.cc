fn render_dendrite_config(
    app: &AppHandle,
    data: &Path,
    pg_port: u16,
    app_port: u16,
    secrets: &HostSecrets,
) -> Result<PathBuf, String> {
    let template_path = bundle_dir(app)?.join("dendrite.yaml.template");
    let template = std::fs::read_to_string(&template_path)
        .map_err(|e| format!("couldn't read dendrite template: {e}"))?;

    let database_url = format!(
        "postgresql://sovrgn:{}@127.0.0.1:{}/dendrite?sslmode=disable",
        secrets.db_password, pg_port
    );

    // Per-install, not the shared "sovrgn.host" this used to hardcode. Read
    // from the data dir so Dendrite and the app cannot disagree about it —
    // they would each produce different Matrix IDs for the same person.
    let server_name = matrix_server_name(data, &secrets.matrix_server_name)?;

    let rendered = template
        .replace("__MATRIX_SERVER_NAME__", &server_name)
        .replace("__MATRIX_SHARED_SECRET__", &secrets.matrix_shared_secret)
        .replace("__DENDRITE_DISABLE_FEDERATION__", "true")
        .replace("__DENDRITE_DATABASE_URL__", &database_url);

    // The same guard the install scripts apply: a placeholder that survives
    // rendering means the template grew a field this code doesn't know.
    for line in rendered.lines() {
        let code = line.trim_start();
        if !code.starts_with('#') && code.contains("__") && code.contains("__MATRIX") {
            return Err(format!("unfilled placeholder in dendrite template: {code}"));
        }
    }

    // The bundled template points private_key at /etc/dendrite; here it lives
    // in the data dir. Rewritten rather than templated so the production
    // template stays exactly what production uses.
    let rendered = rendered.replace(
        "/etc/dendrite/matrix_key.pem",
        &data.join("matrix_key.pem").display().to_string(),
    );

    // Same treatment for the storage paths, and this one was learned from a
    // corpse: the template's /var/lib/dendrite belongs to the systemd install
    // (StateDirectory) and to Docker (a root container writes /var/lib
    // freely). A desktop user cannot mkdir /var/lib/dendrite, and JetStream
    // said exactly that — level=fatal, first boot, every boot — while the
    // harness stayed green on the identical template. Windows quietly
    // tolerated it by creating \var\lib on the current drive, which is why
    // the Windows walk met a live homeserver and this Linux host never did.
    // Every /var/lib/dendrite path is rebased into the data dir; Dendrite
    // creates the subdirectories itself once their parent is writable.
    let rendered = rendered.replace(
        "/var/lib/dendrite",
        &data.join("dendrite").display().to_string(),
    );

    // Dendrite's Windows build fatals on the template's `std` logging hook —
    // log_windows.go recognises only `file` — so the very first Windows boot
    // died in SetupHookLogging before binding a port, and the panel read
    // "starting" forever. The hook is redundant on a desktop host anyway:
    // dendrite logs to stderr unconditionally, and the supervisor captures
    // stderr into dendrite.log on every platform. Dropped everywhere rather
    // than cfg-gated so Linux and Windows render the same config; the
    // production template keeps its hook, same policy as the path rewrites
    // above.
    let rendered = rendered.replace("logging:\n  - type: std\n    level: info", "logging: []");
    if rendered.contains("type: std") {
        // Same guard as the placeholders: a hook that survives rewriting
        // means the template changed shape and this code no longer knows it.
        return Err("dendrite template's std logging hook survived rewriting".to_string());
    }

    // The appservice registration (ADR 0015) — rendered beside the config
    // from the bundle's template, with this start's tokens and this start's
    // app port, and the template's /etc/dendrite path rebased into the data
    // dir exactly as the signing key's is. Dendrite reads it at boot, which
    // is why the app's port has to be known before Dendrite starts, and why
    // the caller picks it early.
    let registration = render_appservice_registration(app, data, app_port, secrets)?;
    let rendered = rendered.replace(
        "/etc/dendrite/appservice.yaml",
        &registration.display().to_string(),
    );
    if rendered.contains("/etc/dendrite/appservice.yaml") || !rendered.contains("app_service_api:") {
        // Same guard as the placeholders: a template that no longer lists the
        // registration would start a homeserver that never tells the instance
        // anything, and every client-authored event would vanish silently.
        return Err("dendrite template's app_service_api section is missing or unrewritten".to_string());
    }

    // The listen port is a CLI flag at spawn, not a config field — the port
    // is picked fresh each start and the config shouldn't pretend otherwise.
    let path = data.join("dendrite.yaml");
    std::fs::write(&path, rendered).map_err(|e| e.to_string())?;
    Ok(path)
}

/// The registration file Dendrite reads to know where to push events, and
/// under which token. Written each start: the app's port is chosen fresh
/// each start, and the file names it.
fn render_appservice_registration(
    app: &AppHandle,
    data: &Path,
    app_port: u16,
    secrets: &HostSecrets,
) -> Result<PathBuf, String> {
    if secrets.appservice_as_token.is_empty() || secrets.appservice_hs_token.is_empty() {
        return Err("the appservice tokens are missing from this install's secrets".to_string());
    }
    let template_path = bundle_dir(app)?.join("appservice.yaml.template");
    let template = std::fs::read_to_string(&template_path).map_err(|e| {
        format!(
            "couldn't read appservice template: {e} — this installer's bundle predates always-on encryption; install a newer one"
        )
    })?;
    let rendered = template
        .replace("{{AS_TOKEN}}", &secrets.appservice_as_token)
        .replace("{{HS_TOKEN}}", &secrets.appservice_hs_token)
        .replace("{{APP_URL}}", &format!("http://127.0.0.1:{app_port}"));
    for line in rendered.lines() {
        let code = line.trim_start();
        if !code.starts_with('#') && code.contains("{{") {
            return Err(format!("unfilled placeholder in appservice template: {code}"));
        }
    }
    let path = data.join("appservice.yaml");
    std::fs::write(&path, rendered).map_err(|e| e.to_string())?;
    Ok(path)
}

/// LiveKit reads its ports and keys from a config file — its own format,
/// like dendrite.yaml, which is the one place secrets are allowed to touch
/// disk. Rendered fresh each start because the port is picked fresh each
/// start.
///
/// Two addresses in here are deliberate. `bind_addresses` is 0.0.0.0 because
/// voice is the one component that must NOT live on loopback: the media has
/// to be dialable by the people on the LAN the server claims to serve.
/// `use_external_ip` is false because a desktop host is a LAN machine — the
/// SFU should advertise the interfaces it actually has, not ask a STUN
/// server for a public address nobody forwarded.
fn render_livekit_config(
    data: &Path,
    port: u16,
    udp: (u16, u16),
    secrets: &HostSecrets,
) -> Result<PathBuf, String> {
    let (udp_start, udp_end) = udp;
    let tcp_port = port + 1; // ICE/TCP fallback beside the ws port — the kubo gateway precedent
    let rendered = format!(
        "# Written by the desktop supervisor each start — hosting.rs.\n\
         port: {port}\n\
         bind_addresses:\n\
         \x20 - \"0.0.0.0\"\n\
         rtc:\n\
         \x20 port_range_start: {udp_start}\n\
         \x20 port_range_end: {udp_end}\n\
         \x20 tcp_port: {tcp_port}\n\
         \x20 use_external_ip: false\n\
         keys:\n\
         \x20 \"{key}\": \"{secret}\"\n",
        key = secrets.livekit_api_key,
        secret = secrets.livekit_api_secret,
    );
    let path = data.join("livekit.yaml");
    std::fs::write(&path, rendered).map_err(|e| e.to_string())?;
    Ok(path)
}

/// Start every component. Returns the final report; the same report is also
/// emitted as an event so the UI can render without racing the invoke.
#[tauri::command]
pub async fn host_start(
    app: AppHandle,
    processes: tauri::State<'_, HostProcesses>,
    secrets: HostSecrets,
    ports: PortPlan,
    options: HostOptions,
) -> Result<HostReport, String> {
    if !installed(&app) {
        return Err("Nothing is installed to start.".to_string());
    }
    // A start is a fresh tunnel or no tunnel; either way, last run's address
    // is not this run's.
    *TUNNEL_URL.lock().unwrap() = None;

    let data = data_dir(&app)?;
    let logs = data.join("logs");
    std::fs::create_dir_all(&logs).map_err(|e| e.to_string())?;

    let mut components: Vec<ComponentReport> = Vec::new();
    let fail = |components: &mut Vec<ComponentReport>, id: &str, error: String| {
        components.push(ComponentReport {
            id: id.to_string(),
            state: "failed".to_string(),
            port: None,
            error: Some(error),
        });
    };

    // -- postgres ------------------------------------------------------------
    let pg_port = pick_port(&ports.postgres)?;
    {
        let mut c = Command::new(postgres_bin(&app, "postgres")?);
        c.arg("-D")
            .arg(data.join("pg"))
            .arg("-p")
            .arg(pg_port.to_string());
        match spawn_logged(c, &logs.join("postgres.log")) {
            Ok(child) => {
                processes.0.lock().unwrap().insert("postgres".into(), child);
                if wait_for_port(pg_port, 30) {
                    components.push(ComponentReport {
                        id: "postgres".into(),
                        state: "running".into(),
                        port: Some(pg_port),
                        error: None,
                    });
                } else {
                    fail(&mut components, "postgres", "didn't accept connections within 30s".into());
                }
            }
            Err(e) => fail(&mut components, "postgres", e),
        }
    }

    // The two databases, created if they don't exist.
    //
    // Not `createdb`. zonky's embedded-postgres binaries — plain PostgreSQL
    // repackaged per platform, which is what the bundle ships — omit the
    // client tools on Windows and Linux and include them on macOS. A bundle
    // built on a Mac therefore worked, shipped, and failed on a user's Windows
    // machine three steps into a first run with "The system cannot find the
    // file specified": a missing file nobody would think to look for, because
    // it was present when the bundle was built.
    //
    // `createdb` is a thin wrapper around `CREATE DATABASE`. Doing it over a
    // connection removes the dependency instead of working around it, and the
    // bundle already carries both Node and the postgres driver. Both databases
    // in one call, and it exits 0 when they already exist — the ordinary
    // second launch is not an error.
    if components.iter().any(|c| c.id == "postgres" && c.state == "running") {
        let bundle = bundle_dir(&app)?;
        let mut c = Command::new(bundle.join(exe("node")));
        c.arg(bundle.join("app").join("createdbs.mjs"))
            .arg("sovrgnnet")
            .arg("dendrite")
            .env("PGHOST", "127.0.0.1")
            .env("PGPORT", pg_port.to_string())
            .env("PGUSER", "sovrgn")
            .env("PGPASSWORD", &secrets.db_password);
        run_to_completion(c, "create databases")?;
    }

    // The app's port, chosen here rather than beside the app, because the
    // appservice registration Dendrite reads at boot names it (ADR 0015).
    // Bind-and-release like every pick; the window between this and the
    // app's spawn is a few components long, and the same race already
    // existed between each pick and its own spawn.
    let app_port = pick_port(&ports.app)?;

    // -- dendrite ------------------------------------------------------------
    let matrix_port = pick_port(&ports.matrix)?;
    match render_dendrite_config(&app, &data, pg_port, app_port, &secrets) {
        Ok(config) => {
            let mut c = Command::new(bundle_dir(&app)?.join(exe("dendrite")));
            c.arg("--config")
                .arg(&config)
                .arg("--http-bind-address")
                .arg(format!("127.0.0.1:{matrix_port}"));
            match spawn_logged(c, &logs.join("dendrite.log")) {
                Ok(child) => {
                    processes.0.lock().unwrap().insert("matrix".into(), child);
                    components.push(ComponentReport {
                        id: "matrix".into(),
                        state: if wait_for_port(matrix_port, 60) { "running" } else { "starting" }.into(),
                        port: Some(matrix_port),
                        error: None,
                    });
                }
                Err(e) => fail(&mut components, "matrix", e),
            }
        }
        Err(e) => fail(&mut components, "matrix", e),
    }

    // -- kubo ----------------------------------------------------------------
    let ipfs_port = pick_port(&ports.ipfs)?;
    {
        // The repo's addresses are rewritten each start, because the port is
        // picked each start. Kubo reads them from its config, not flags.
        for (key, value) in [
            ("Addresses.API", format!("\"/ip4/127.0.0.1/tcp/{ipfs_port}\"")),
            ("Addresses.Gateway", format!("\"/ip4/127.0.0.1/tcp/{}\"", ipfs_port + 1)),
        ] {
            let mut c = Command::new(bundle_dir(&app)?.join(exe("kubo")));
            c.arg("config").arg("--json").arg(key).arg(&value).env("IPFS_PATH", data.join("ipfs"));
            if let Err(e) = run_to_completion(c, &format!("ipfs config {key}")) {
                fail(&mut components, "ipfs", e);
                break;
            }
        }
        if !components.iter().any(|c| c.id == "ipfs") {
            let mut c = Command::new(bundle_dir(&app)?.join(exe("kubo")));
            c.arg("daemon").env("IPFS_PATH", data.join("ipfs"));
            match spawn_logged(c, &logs.join("ipfs.log")) {
                Ok(child) => {
                    processes.0.lock().unwrap().insert("ipfs".into(), child);
                    components.push(ComponentReport {
                        id: "ipfs".into(),
                        state: "starting".into(), // fine to be late; chat doesn't wait for files
                        port: Some(ipfs_port),
                        error: None,
                    });
                }
                Err(e) => fail(&mut components, "ipfs", e),
            }
        }
    }

    // -- livekit (voice) -----------------------------------------------------
    // What makes `voice: true` true on a desktop-hosted instance — ADR 0013
    // as superseded: every instance houses its own voice backend, and a
    // laptop is an instance. Deliberately optional twice over: an older
    // bundle has no binary, an older keychain (not yet backfilled by the
    // frontend) has no keys, and either way the app below simply never
    // receives LIVEKIT_* — the instance advertises voice: false rather than
    // failing, exactly the posture a dedicated deployment takes when its
    // operator hasn't set the three env lines.
    //
    // Skipping is a state, not an absence. The first version of this block
    // pushed nothing when the gate didn't pass, and the first real walk of
    // the voice release probed a machine and found three silences — no
    // process, no config, no log — with nothing anywhere saying whether
    // voice had been skipped, had crashed, or had never been reached. A
    // person cannot tell "off on purpose" from "broken" unless the
    // supervisor says which, so it says which: an "off" row with the reason
    // in words, held in VOICE_OFF_REASON so host_state polls (which rebuild
    // from live processes) keep saying it.
    //
    // Reported as "starting" without waiting, the kubo reasoning: chat
    // doesn't wait for voice, and the next host_state poll tells the truth.
    let mut voice_port: Option<u16> = None;
    {
        let livekit = bundle_dir(&app)?.join(exe("livekit"));
        let have_binary = livekit.exists();
        let have_keys = !secrets.livekit_api_key.is_empty()
            && !secrets.livekit_api_secret.is_empty();
        *VOICE_OFF_REASON.lock().unwrap() = None;
        if have_binary && have_keys {
            match pick_port(&ports.voice) {
                Ok(port) => match render_livekit_config(&data, port, ports.voice_udp, &secrets) {
                    Ok(config) => {
                        let mut c = Command::new(&livekit);
                        c.arg("--config").arg(&config);
                        match spawn_logged(c, &logs.join("livekit.log")) {
                            Ok(child) => {
                                processes.0.lock().unwrap().insert("voice".into(), child);
                                voice_port = Some(port);
                                components.push(ComponentReport {
                                    id: "voice".into(),
                                    state: "starting".into(),
                                    port: Some(port),
                                    error: None,
                                });
                            }
                            Err(e) => fail(&mut components, "voice", e),
                        }
                    }
                    Err(e) => fail(&mut components, "voice", e),
                },
                Err(e) => fail(&mut components, "voice", e),
            }
        } else {
            let reason = if !have_binary {
                // Only release bundles carry the SFU; a bundle assembled
                // before the voice release simply doesn't have the file.
                "this bundle carries no voice server — chat is unaffected"
            } else {
                // hostSecrets() backfills the pair before every start, so an
                // empty key here means the keychain refused to hand it over.
                "no voice signing pair — the keychain didn't provide one at start"
            };
            *VOICE_OFF_REASON.lock().unwrap() = Some(reason.to_string());
            components.push(ComponentReport {
                id: "voice".into(),
                state: "off".into(),
                port: None,
                error: Some(reason.to_string()),
            });
        }
    }

    // -- tunnel --------------------------------------------------------------
    //
    // Before the app, for the reason shared/hosting.ts gives beside voice:
    // the app reads its public hostname from the environment at boot, and a
    // quick tunnel's hostname exists only once cloudflared has connected.
    // cloudflared is content to come up before its origin does — it answers
    // 502 until the app is listening, then stops — so the ordering costs
    // nothing but the wait.
    let mut public_url: Option<String> = None;
    if options.wants_tunnel() {
        match spawn_tunnel(&bundle_dir(&app)?, app_port, &logs.join("tunnel.log")) {
            Ok(child) => {
                processes.0.lock().unwrap().insert("tunnel".into(), child);
                public_url = wait_for_tunnel_url(30);
                components.push(ComponentReport {
                    id: "tunnel".into(),
                    state: if public_url.is_some() { "running" } else { "starting" }.into(),
                    port: None,
                    error: None,
                });
            }
            Err(e) => fail(&mut components, "tunnel", e),
        }
    }

    // -- app -----------------------------------------------------------------
    {
        let bundle = bundle_dir(&app)?;
        let mut c = Command::new(bundle.join(exe("node")));
        c.arg(bundle.join("app").join("index.mjs"))
            .current_dir(bundle.join("app"))
            .env("NODE_ENV", "production")
            .env("PORT", app_port.to_string())
            .env(
                "DATABASE_URL",
                format!(
                    "postgresql://sovrgn:{}@127.0.0.1:{}/sovrgnnet",
                    secrets.db_password, pg_port
                ),
            )
            .env("JWT_SECRET", &secrets.jwt_secret)
            .env("MATRIX_SHARED_SECRET", &secrets.matrix_shared_secret)
            // Same value Dendrite was rendered with, from the same file. If
            // these two ever diverge, the app mints @alice:a while the
            // homeserver only knows @alice:b, and every login fails with
            // M_FORBIDDEN saying nothing about why.
            .env("MATRIX_SERVER_NAME", &matrix_server_name(&data, &secrets.matrix_server_name)?)
            .env("MATRIX_HOMESERVER_URL", format!("http://127.0.0.1:{matrix_port}"))
            .env("IPFS_API_URL", format!("http://127.0.0.1:{ipfs_port}"))
            .env("SOVRGN_SETUP_TOKEN", &secrets.setup_token)
            // The same two values Dendrite's registration was rendered with
            // (ADR 0015). If these ever diverge, every push the homeserver
            // makes is a 403 in app.log and an index that silently stops
            // following the rooms it is supposed to mirror.
            .env("MATRIX_APPSERVICE_AS_TOKEN", &secrets.appservice_as_token)
            .env("MATRIX_APPSERVICE_HS_TOKEN", &secrets.appservice_hs_token)
            .env("INSTANCE_NAME", "My computer")
            .env("INSTANCE_JOIN_POLICY", "invite")
            .env("SOVRGNNET_ACCESS_MODE", if options.wants_tunnel() { "tunnel" } else { "lan" });
        // The one address that is right for everyone, handed to the app so
        // invite links name it instead of the owner's loopback
        // (server/lanHost.ts). Only when known: an app started with a stale
        // or guessed public host would mint links to nowhere with total
        // confidence, which is worse than LAN links that at least say where
        // they point.
        if let Some(url) = &public_url {
            c.env("SOVRGN_PUBLIC_HOST", url);
        }
        // Only when the SFU actually started: these three are the exact
        // switch behind the instance's `voice` capability flag, and setting
        // them beside a component that failed to spawn would advertise a
        // capability that isn't there. Loopback is correct here — the server
        // substitutes the caller's own host at voice.join, the invite-link
        // treatment (server/lanHost.ts).
        if let Some(port) = voice_port {
            c.env("LIVEKIT_URL", format!("ws://127.0.0.1:{port}"))
                .env("LIVEKIT_API_KEY", &secrets.livekit_api_key)
                .env("LIVEKIT_API_SECRET", &secrets.livekit_api_secret);
        }
        // First boot applies migrations; the step is announced so the pause
        // reads as work rather than a hang.
        emit_step(&app, "migrate");
        match spawn_logged(c, &logs.join("app.log")) {
            Ok(child) => {
                emit_step(&app, "start");
                processes.0.lock().unwrap().insert("app".into(), child);
                components.push(ComponentReport {
                    id: "app".into(),
                    state: if wait_for_port(app_port, 90) { "running" } else { "starting" }.into(),
                    port: Some(app_port),
                    error: None,
                });
            }
            Err(e) => fail(&mut components, "app", e),
        }
    }

    let url = components
        .iter()
        .find(|c| c.id == "app" && c.state == "running")
        .and_then(|c| c.port)
        .map(|p| format!("http://127.0.0.1:{p}"));

    let report = HostReport {
        installed: true,
        components,
        url,
        public_url,
    };
    emit_state(&app, &report);
    Ok(report)
}

