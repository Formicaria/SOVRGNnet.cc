/// Stop everything, most-dependent first. Postgres goes through pg_ctl so it
/// checkpoints instead of recovering on next start; the single-process Go and
/// Node components are killed, which their databases are built to survive.
#[tauri::command]
pub async fn host_stop(
    app: AppHandle,
    processes: tauri::State<'_, HostProcesses>,
) -> Result<(), String> {
    stop_all(&app, &processes);
    Ok(())
}

pub fn stop_all(app: &AppHandle, processes: &HostProcesses) {
    // A stopped server has no voice row to explain. The reason belongs to a
    // running-but-voiceless host; leaving it set would make host_state report
    // an "off" SFU for a server that is entirely off.
    *VOICE_OFF_REASON.lock().unwrap() = None;
    *TUNNEL_URL.lock().unwrap() = None;

    let mut map = processes.0.lock().unwrap();

    // The tunnel goes first: it is the only component with a public face, and
    // a public address that answers 502 for the seconds the app takes to die
    // is a worse last impression than one that simply stops resolving.
    for id in ["tunnel", "app", "voice", "ipfs", "matrix"] {
        if let Some(mut child) = map.remove(id) {
            let _ = child.kill();
            let _ = child.wait();
        }
    }

    if let Some(mut child) = map.remove("postgres") {
        let stopped = data_dir(app)
            .and_then(|data| {
                run_to_completion(
                    {
                        let mut c = Command::new(postgres_bin(app, "pg_ctl")?);
                        c.arg("stop").arg("-D").arg(data.join("pg")).arg("-m").arg("fast");
                        c
                    },
                    "pg_ctl stop",
                )
            })
            .is_ok();
        if !stopped {
            let _ = child.kill();
        }
        let _ = child.wait();
    }
}

// --------------------------------------------------------------------- state

/// The current picture: what's installed, what's running, what died.
///
/// A child that exited is reported as failed with whatever exit status it
/// left, which is how the frontend learns about a crash between polls.
#[tauri::command]
pub async fn host_state(
    app: AppHandle,
    processes: tauri::State<'_, HostProcesses>,
) -> Result<HostReport, String> {
    let mut components = Vec::new();
    let mut map = processes.0.lock().unwrap();

    let public_url = TUNNEL_URL.lock().unwrap().clone();

    for (id, child) in map.iter_mut() {
        let state = match child.try_wait() {
            // Alive is running — except for the tunnel, which is alive from
            // the moment it spawns and *useful* only once it has an address.
            // Reporting the gap as "starting" is what lets the panel show a
            // spinner beside "public link" instead of a green dot beside
            // nothing.
            Ok(None) if id == "tunnel" && public_url.is_none() => ("starting".to_string(), None),
            Ok(None) => ("running".to_string(), None),
            Ok(Some(status)) => ("failed".to_string(), Some(format!("exited: {status}"))),
            Err(e) => ("failed".to_string(), Some(e.to_string())),
        };
        components.push(ComponentReport {
            id: id.clone(),
            state: state.0,
            port: None,
            error: state.1,
        });
    }

    // A deliberately-off SFU has no child to poll; keep saying why it's off,
    // or the panel's voice row exists for one report and then evaporates.
    if let Some(reason) = VOICE_OFF_REASON.lock().unwrap().clone() {
        components.push(ComponentReport {
            id: "voice".into(),
            state: "off".into(),
            port: None,
            error: Some(reason),
        });
    }

    Ok(HostReport {
        installed: installed(&app),
        components,
        url: None,
        public_url,
    })
}

/// Whether this build can host at all, and whether it already does.
#[tauri::command]
pub async fn host_available(app: AppHandle) -> Result<serde_json::Value, String> {
    Ok(serde_json::json!({
        "bundled": bundle_present(&app),
        "installed": installed(&app),
    }))
}

